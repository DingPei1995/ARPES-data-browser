"""One-off generator: turns Table 1-1 of the X-ray Data Booklet ("Electron
binding energies, in electron volts, for the elements in their natural
forms", ``Table_1-1.pdf`` at the top of the repository) into the constant
table ``tools/spectra/corelevel_table.py``, so the core-level check never reads the
PDF at run time.

The PDF's text is pulled out with poppler's ``pdftotext -layout``. Every
row is written left to right without gaps -- a light element simply stops
after its last shell, and a missing value inside a row is printed as an
em dash -- so the values can be read in column order without measuring
where each column sits on the page. The footnote marks (``*``, ``†``,
``a``, ``b``) are dropped; one typo in the PDF (Cd 4d5/2 printed as
``l0.7``, with a letter l) is read as 10.7.

Usage:  python devtools/gen_corelevels.py [Table_1-1.pdf]   (needs pdftotext)
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_PDF = os.path.join(os.path.dirname(HERE), "Table_1-1.pdf")
OUTPUT = os.path.join(HERE, "tools", "spectra", "corelevel_table.py")

#: The column order of the two kinds of page in the table.
INNER = ("1s", "2s", "2p1/2", "2p3/2", "3s", "3p1/2", "3p3/2", "3d3/2",
         "3d5/2", "4s", "4p1/2", "4p3/2")
OUTER = ("4d3/2", "4d5/2", "4f5/2", "4f7/2", "5s", "5p1/2", "5p3/2",
         "5d3/2", "5d5/2", "6s", "6p1/2", "6p3/2")

ROW = re.compile(r"^\s*(\d{1,2})\s+([A-Z][a-z]?)\s+(.*)$")
MARKS = "*†ab"


def _value(token: str):
    token = token.replace("l0.7", "10.7")
    if token in ("—", "-", "–"):
        return None
    number = token.rstrip(MARKS)
    return float(number)


def parse(text: str) -> dict:
    """``{Z: (symbol, {orbital: eV})}`` from the PDF's text."""
    table, columns = {}, None
    for line in text.splitlines():
        if line.strip().startswith("Element"):
            columns = OUTER if "N4" in line else INNER
            continue
        match = ROW.match(line)
        if not match or columns is None:
            continue
        z, symbol, rest = int(match.group(1)), match.group(2), match.group(3)
        tokens = [t for t in rest.split() if t.strip(MARKS)]
        values = [_value(t) for t in tokens]
        if len(values) > len(columns):
            raise ValueError(f"{symbol}: {len(values)} values for "
                             f"{len(columns)} columns: {rest!r}")
        entry = table.setdefault(z, (symbol, {}))[1]
        for orbital, value in zip(columns, values):
            if value is not None:
                entry[orbital] = value
    return table


def render(table: dict) -> str:
    lines = [
        '"""',
        "tools/spectra/corelevel_table.py -- AUTO-GENERATED by devtools/gen_corelevels.py.",
        "Do not edit by hand.",
        "",
        "Electron binding energies (eV) of the elements in their natural forms,",
        "from Table 1-1 of the X-ray Data Booklet (J. A. Bearden & A. F. Burr,",
        "Rev. Mod. Phys. 39, 125 (1967); M. Cardona & L. Ley, Photoemission in",
        "Solids I (1978); J. C. Fuggle & N. Martensson, J. Electron Spectrosc.",
        "21, 37 (1980)). The table's own note: energies are relative to the",
        "vacuum level for the rare gases and for H2, N2, O2, F2 and Cl2, to the",
        "Fermi level for the metals, and to the top of the valence band for",
        "semiconductors.",
        "",
        "``BINDING_ENERGIES[symbol]`` is ``{orbital: eV}``; the orbital names are",
        "``1s``, ``2p3/2``, ``4f7/2`` and so on.",
        '"""',
        "",
        "#: atomic number -> symbol, for the elements in the table (H to U).",
        "ELEMENTS = {",
    ]
    for z in sorted(table):
        lines.append(f"    {z}: {table[z][0]!r},")
    lines += ["}", "", "BINDING_ENERGIES = {"]
    for z in sorted(table):
        symbol, levels = table[z]
        body = ", ".join(f"{k!r}: {v!r}" for k, v in levels.items())
        lines.append(f"    {symbol!r}: {{{body}}},")
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv):
    pdf = argv[1] if len(argv) > 1 else DEFAULT_PDF
    text = subprocess.run(["pdftotext", "-layout", pdf, "-"], check=True,
                          capture_output=True, text=True).stdout
    table = parse(text)
    missing = [z for z in range(1, 93) if z not in table]
    if missing:
        raise SystemExit(f"rows missing from the table: {missing}")
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(render(table))
    print(f"wrote {OUTPUT}: {len(table)} elements, "
          f"{sum(len(v[1]) for v in table.values())} levels")


if __name__ == "__main__":
    main(sys.argv)
